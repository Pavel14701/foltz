def _steps(*items: str) -> str:
    """Нумерованный список шагов для секции «Как проходит работа»."""
    return chr(10).join(f'{i}. {item}' for i, item in enumerate(items, 1))


def _svc(title, slug, preview, prices, how, why, adv, extra=()):
    """Собирает услугу: продающий текст + секции + прайс."""
    sections = [
        {'order': 1, 'subtitle': 'Как проходит работа у нас'},
        {'order': 2, 'content': how},
        {'order': 3, 'subtitle': 'Почему это стоит именно столько'},
        {'order': 4, 'content': why},
        {'order': 5, 'subtitle': 'Почему выбирают нас'},
        {'order': 6, 'content': adv},
    ]
    for i, (sub, content) in enumerate(extra, start=len(sections) + 1):
        if sub:
            sections.append({'order': i, 'subtitle': sub})
            sections.append({'order': i + 1, 'content': content})
        else:
            sections.append({'order': i, 'content': content})
    return {
        'title': title,
        'slug': slug,
        'preview_text': preview,
        'prices': prices,
        'sections': sections,
    }


